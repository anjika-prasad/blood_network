-- ---------- Compatibility matrix (red cells), generated by rule -----
-- ABO ok  : donor is O, OR recipient is AB, OR same ABO
-- Rh ok   : donor is Rh-, OR recipient is Rh+
INSERT INTO blood_compatibility (recipient_group_id, donor_group_id)
SELECT r.group_id, d.group_id
FROM   blood_group r CROSS JOIN blood_group d
WHERE  (d.abo = 'O' OR r.abo = 'AB' OR d.abo = r.abo)
AND    (d.rh = '-' OR r.rh = '+');
-- sanity check: must be 27 rows
SELECT COUNT(*) AS compatibility_rows FROM blood_compatibility;

