-- ---------- Donors: one guaranteed per group + 32 random ------------
INSERT INTO donor (full_name, date_of_birth, gender, phone, group_id)
SELECT 'Seed Donor ' || g.group_name, ADD_MONTHS(TRUNC(SYSDATE), -12 * 30), 'M',
       '98000000' || g.group_id, g.group_id
FROM   blood_group g;

DECLARE
  v_r NUMBER; v_gid NUMBER;
BEGIN
  DBMS_RANDOM.SEED(2026);
  FOR i IN 1 .. 32 LOOP
    v_r := DBMS_RANDOM.VALUE(0, 100);
    -- approximate real-world group frequencies
    v_gid := CASE WHEN v_r < 36 THEN 2  WHEN v_r < 64 THEN 4  WHEN v_r < 85 THEN 6
                  WHEN v_r < 90 THEN 8  WHEN v_r < 93 THEN 1  WHEN v_r < 96 THEN 3
                  WHEN v_r < 98 THEN 5  ELSE 7 END;
    INSERT INTO donor (full_name, date_of_birth, gender, phone, group_id)
    VALUES ('Donor ' || LPAD(i, 3, '0'),
            ADD_MONTHS(TRUNC(SYSDATE), -12 * TRUNC(DBMS_RANDOM.VALUE(20, 55))),
            CASE WHEN DBMS_RANDOM.VALUE(0, 1) < 0.5 THEN 'M' ELSE 'F' END,
            '97000' || LPAD(i, 5, '0'), v_gid);
  END LOOP;
END;
/

-- ---------- 250 blood units, deliberately imbalanced ----------------
-- Hospital 1 hoards stock (45%), hospital 4 is starved (10%) - the
-- "wastage next to shortage" situation from the problem statement.
-- Ages 0-48 days: roughly 12% arrive already expired (trigger marks them EXPIRED).
DECLARE
  v_donor NUMBER; v_hosp NUMBER; v_r NUMBER;
BEGIN
  DBMS_RANDOM.SEED(2026);
  FOR i IN 1 .. 250 LOOP
    SELECT donor_id INTO v_donor
    FROM  (SELECT donor_id FROM donor ORDER BY DBMS_RANDOM.VALUE) WHERE ROWNUM = 1;
    v_r := DBMS_RANDOM.VALUE(0, 100);
    v_hosp := CASE WHEN v_r < 45 THEN 1 WHEN v_r < 75 THEN 2 WHEN v_r < 90 THEN 3 ELSE 4 END;
    INSERT INTO blood_unit (donor_id, hospital_id, collection_date)
    VALUES (v_donor, v_hosp, TRUNC(SYSDATE) - TRUNC(DBMS_RANDOM.VALUE(0, 49)));
  END LOOP;
END;
/

-- ---------- 15 open requests ---------------------------------------
DECLARE
  v_r NUMBER; v_g NUMBER;
BEGIN
  DBMS_RANDOM.SEED(99);
  FOR i IN 1 .. 15 LOOP
    v_r := DBMS_RANDOM.VALUE(0, 100);
    v_g := CASE WHEN v_r < 36 THEN 2 WHEN v_r < 64 THEN 4 WHEN v_r < 85 THEN 6
                WHEN v_r < 90 THEN 8 WHEN v_r < 93 THEN 1 WHEN v_r < 96 THEN 3
                WHEN v_r < 98 THEN 5 ELSE 7 END;
    INSERT INTO patient_request (hospital_id, patient_ref, group_id, units_required, urgency)
    VALUES (TRUNC(DBMS_RANDOM.VALUE(1, 5)), 'MRN-' || LPAD(i, 5, '0'), v_g,
            TRUNC(DBMS_RANDOM.VALUE(1, 4)),
            CASE WHEN DBMS_RANDOM.VALUE(0, 1) < 0.2 THEN 'CRITICAL'
                 WHEN DBMS_RANDOM.VALUE(0, 1) < 0.5 THEN 'URGENT' ELSE 'ROUTINE' END);
  END LOOP;
END;
/
COMMIT;

