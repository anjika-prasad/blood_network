-- Allocate every open request (commit after each: one transaction per request)
BEGIN
  FOR r IN (SELECT request_id FROM patient_request
            WHERE status IN ('PENDING','PARTIAL') ORDER BY
                  DECODE(urgency,'CRITICAL',1,'URGENT',2,3), request_time) LOOP
    allocate_request(r.request_id);
    COMMIT;
  END LOOP;
END;
